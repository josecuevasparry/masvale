/**
 * One-off helper: downloads the Open Sans (latin + latin-ext) woff2 files
 * used by the site into public/fonts and writes src/styles/fonts.css.
 * Run with: node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontDir = join(root, "public", "fonts");
const cssOut = join(root, "src", "styles", "fonts.css");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";
const WEIGHTS = [300, 400, 600, 700, 900];
const FAMILY = "Open Sans";

await mkdir(fontDir, { recursive: true });
await mkdir(dirname(cssOut), { recursive: true });

const url = `https://fonts.googleapis.com/css2?family=${FAMILY.replace(
  / /g,
  "+"
)}:wght@${WEIGHTS.join(";")}&display=swap`;

const res = await fetch(url, { headers: { "User-Agent": UA } });
if (!res.ok) throw new Error(`Google Fonts responded ${res.status}`);
const css = await res.text();

// Split the response into @font-face blocks and keep the latin / latin-ext ones.
const blocks = css.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) ?? [];
const kept = [];

for (const block of blocks) {
  const subset = block.match(/\/\*\s*([a-z-]+)\s*\*\//)?.[1] ?? "latin";
  if (subset !== "latin" && subset !== "latin-ext") continue;

  const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
  const style = block.match(/font-style:\s*(\w+)/)?.[1] ?? "normal";
  const src = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
  const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
  if (!src || !weight) continue;

  const file = `${FAMILY.replace(/ /g, "-").toLowerCase()}-${weight}-${subset}.woff2`;
  const bin = await fetch(src, { headers: { "User-Agent": UA } });
  if (!bin.ok) throw new Error(`Font ${file} responded ${bin.status}`);
  await writeFile(join(fontDir, file), Buffer.from(await bin.arrayBuffer()));
  console.log(`saved public/fonts/${file}`);

  kept.push({ weight, style, file, range });
}

const faceCss = kept
  .map(
    ({ weight, style, file, range }) => `@font-face {
  font-family: "${FAMILY}";
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url("../../public/fonts/${file}") format("woff2");
${range ? `  unicode-range: ${range};\n` : ""}}`
  )
  .join("\n\n");

await writeFile(
  cssOut,
  `/* Generated by scripts/fetch-fonts.mjs - do not edit by hand. */\n\n${faceCss}\n`
);
console.log(`wrote src/styles/fonts.css (${kept.length} faces)`);
